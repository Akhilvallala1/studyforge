class ReteachProvider:
    """Returns a well-formed remedial note, with exact token counts and no price."""

    name = "fake"
    model = "reteach-model"
    is_paid = False

    def __init__(self):
        self.calls = 0

    def generate(self, system: str, prompt: str, max_tokens: int = 64000):
        self.calls += 1
        text = json.dumps(
            {
                "restatement": "The idea again, in plainer words.",
                "worked_example": "Step one, then step two, and that is why it follows.",
            }
        )
        return LLMResult(text=text, input_tokens=120, output_tokens=60)


class OutlineThenFails:
    """A generation run that dies on the lesson stage after paying for the outline."""

    name = "anthropic"
    model = "claude-opus-5"
    is_paid = True

    def __init__(self):
        self.calls = 0

    def generate(self, system: str, prompt: str, max_tokens: int = 64000):
        self.calls += 1
        if self.calls == 1:
            text = json.dumps(
                {
                    "title": "Doomed Course",
                    "description": "Never reaches _save_course",
                    "modules": [
                        {"title": "Module 1", "lessons": [{"title": "Lesson A", "summary": "s"}]}
                    ],
                }
            )
            return LLMResult(text=text, input_tokens=100, output_tokens=50)
        raise LLMCallError("simulated mid-run failure", input_tokens=20, output_tokens=0)


class UnpricedPaidProvider:
    """A paid provider whose model id costs.PRICING has never heard of.

    Not a contrivance: a model released after that table was last updated looks exactly
    like this. Token counts are exact and the PRICE is the fallback, which is the case
    the approximate notice used to describe as a missing token count.
    """

    name = "anthropic"
    model = "vendor-model-absent-from-the-pricing-table"
    is_paid = True

    def __init__(self):
        self.calls = 0

    def generate(self, system: str, prompt: str, max_tokens: int = 64000):
        self.calls += 1
        if "curriculum designer" in system:
            text = json.dumps(
                {
                    "title": "Unpriced Course",
                    "description": "Generated by a model with no pricing entry",
                    "modules": [
                        {"title": "Module 1", "lessons": [{"title": "Lesson A", "summary": "s"}]}
                    ],
                }
            )
        else:
            text = json.dumps(
                {
                    "content": "# Lesson\nStub content",
                    "concepts": ["concept-1"],
                    "quiz": [
                        {
                            "question": "Q?",
                            "kind": "short",
                            "options": [],
                            "answer": "a",
                            "concept": "concept-1",
                        }
                    ],
                }
            )
        return LLMResult(text=text, input_tokens=1000, output_tokens=500)


