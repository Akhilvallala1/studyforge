def _seed_struggling_concept(course_count: int) -> tuple[int, list[int]]:
    """One concept taught by `course_count` courses, rated badly enough to be flagged.

    The label is unique per call because concept keys are global and the test database
    is shared across the suite: a fixed label would let one test's courses decide
    whether another test's concept can be traced to exactly one course.
    """
    label = f"Concept {uuid4().hex[:8]}"
    key = normalize_concept(label)
    course_ids: list[int] = []
    session = SessionLocal()
    try:
        for index in range(course_count):
            course = models.Course(title=f"Course {index} teaching {label}", description="")
            module = models.Module(title="Module 1", position=0)
            lesson = models.Lesson(
                title=f"Lesson {index} on {label}",
                position=0,
                content=f"{label} is the idea under test, explained at some length.",
                concepts=[label],
            )
            lesson.quiz_items.append(
                models.QuizItem(
                    question=f"What is {label}?",
                    kind="short",
                    options=[],
                    answer="the idea under test",
                    concept=label,
                )
            )
            module.lessons.append(lesson)
            course.modules.append(module)
            session.add(course)
            session.commit()
            course_ids.append(course.id)

        # Two lapses inside review.ATTENTION_WINDOW is exactly what needs_attention
        # triggers on, and that trigger is the only way to reach the endpoint.
        moment = datetime.now(UTC).replace(tzinfo=None) - timedelta(days=4)
        for rating in (fsrs.AGAIN, fsrs.AGAIN, fsrs.GOOD):
            review.record_review(session, key, label, rating, now=moment)
            moment += timedelta(days=1)
        session.commit()
        return review.get_card(session, key).id, course_ids
    finally:
        session.close()


def _newest_remediation_call() -> models.LlmCall:
    session = SessionLocal()
    try:
        return (
            session.query(models.LlmCall)
            .filter(models.LlmCall.stage == remediation.REMEDIATION_STAGE)
            .order_by(models.LlmCall.id.desc())
            .first()
        )
    finally:
        session.close()


def _group(usage: dict, group: str) -> dict | None:
    return next((row for row in usage["per_course"] if row["group"] == group), None)


def _course_group(usage: dict, course_id: int) -> dict | None:
    return next((row for row in usage["per_course"] if row["course_id"] == course_id), None)


def _calls_in(row: dict | None) -> int:
    return 0 if row is None else row["calls"]


def _isolated_session():
    """A private database, so a test can assert about the whole llm_calls table.

    The suite shares one SQLite file and every test adds rows to it, which is fine for
    counting deltas but not for "is anything in here approximate", where the answer
    has to be about the rows this test wrote and nothing else.
    """
    engine = create_engine("sqlite://")
    Base.metadata.create_all(engine)
    return sessionmaker(bind=engine)()


def _record_call(session, **overrides) -> None:
    row = {
        "run_id": "r",
        "provider": "anthropic",
        "model": "claude-opus-5",
        "stage": "lesson",
        "course_id": None,
        "input_tokens": 100,
        "output_tokens": 50,
        "estimated_cost_usd": 0.001,
        "approximate": False,
    }
    session.add(models.LlmCall(**(row | overrides)))
    session.commit()


