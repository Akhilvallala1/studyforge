def test_approximate_notice_names_the_price_when_the_price_was_the_estimate():
    """QA's second finding: exact tokens, unpriced model, and the page blamed the tokens."""
    session = _isolated_session()
    try:
        _record_call(session, model="fake", approximate=True)
        assert main._approximation_causes(session) == (False, True)

        note = main.APPROXIMATE_NOTES[(False, True)]
        assert "pricing table" in note
        assert "token counts are exact" in note
        assert "missing an exact token count" not in note
    finally:
        session.close()


def test_approximate_notice_names_the_token_count_when_a_count_was_missing():
    session = _isolated_session()
    try:
        _record_call(session, output_tokens=None, approximate=True)
        assert main._approximation_causes(session) == (True, False)

        note = main.APPROXIMATE_NOTES[(True, False)]
        assert "missing an exact token count" in note
        assert "pricing table" not in note
    finally:
        session.close()


def test_approximate_notice_names_both_causes_when_both_happened():
    session = _isolated_session()
    try:
        _record_call(session, model="fake", approximate=True)
        _record_call(session, output_tokens=None, approximate=True)
        assert main._approximation_causes(session) == (True, True)

        note = main.APPROXIMATE_NOTES[(True, True)]
        assert "pricing table" in note
        assert "missing an exact token count" in note
    finally:
        session.close()


def test_no_approximate_notice_when_every_call_was_exact_and_priced():
    session = _isolated_session()
    try:
        _record_call(session)
        assert main._approximation_causes(session) == (False, False)
        assert main.APPROXIMATE_NOTES.get((False, False)) is None
    finally:
        session.close()


def test_usage_blames_the_pricing_table_not_the_token_counts(client, monkeypatch):
    """End to end, against the real endpoint, for the case QA hit.

    Left last in the file on purpose: it is the first thing in the suite to record an
    approximate call, and the shared test database keeps it for good.
    """
    monkeypatch.delenv("STUDYFORGE_COST_LIMIT_USD", raising=False)
    monkeypatch.setattr(main, "get_provider", lambda: UnpricedPaidProvider())

    generated = client.post("/courses/generate", json={"text": "Priced by no table."})
    assert generated.status_code == 200

    session = SessionLocal()
    try:
        missing_counts = (
            session.query(models.LlmCall)
            .filter(
                or_(
                    models.LlmCall.input_tokens.is_(None),
                    models.LlmCall.output_tokens.is_(None),
                )
            )
            .count()
        )
    finally:
        session.close()
    assert missing_counts == 0, "no recorded call is missing a token count"

    totals = client.get("/usage").json()["totals"]
    assert totals["approximate"] is True
    assert totals["approximate_note"] == main.APPROXIMATE_NOTES[(False, True)]
