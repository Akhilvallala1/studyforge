def test_reteach_is_charged_to_the_one_course_that_teaches_the_concept(client, monkeypatch):
    """The learner looks for re-teaching spend under the course they were re-taught."""
    provider = ReteachProvider()
    monkeypatch.setattr(main, "get_provider", lambda: provider)
    card_id, (course_id,) = _seed_struggling_concept(1)

    assert client.post(f"/review/cards/{card_id}/remediation").status_code == 200
    assert provider.calls == 1

    assert _newest_remediation_call().course_id == course_id

    usage = client.get("/usage").json()
    charged = _course_group(usage, course_id)
    assert charged is not None, "the re-teach was not charged to its course"
    assert charged["group"] == "course"
    assert charged["calls"] == 1  # this course was never generated, only re-taught
    assert charged["label"] == charged["title"]
    assert charged["note"] is None  # a course row needs no explaining
    assert _group(usage, "remediation") is None


def test_reteach_across_two_courses_stays_unattributed_and_is_not_called_a_failure(
    client, monkeypatch
):
    """The defect from the other side: a concept two courses teach has no one owner.

    Naming either course would put a real dollar figure against a course that did not
    earn it, so the call stays unattributed. What must not happen is the page then
    reporting a re-teach the learner watched succeed as a run that failed.
    """
    provider = ReteachProvider()
    monkeypatch.setattr(main, "get_provider", lambda: provider)
    card_id, course_ids = _seed_struggling_concept(2)

    failed_before = _calls_in(_group(client.get("/usage").json(), "failed_run"))

    assert client.post(f"/review/cards/{card_id}/remediation").status_code == 200
    assert _newest_remediation_call().course_id is None

    usage = client.get("/usage").json()
    reteach = _group(usage, "remediation")
    assert reteach is not None
    assert reteach["course_id"] is None
    assert reteach["label"] == "Re-teaching (no single course)"
    assert reteach["note"] == main.GROUP_NOTES[main.GROUP_REMEDIATION]
    # The whole point: this spend is not described as a failure of any kind.
    assert "fail" not in reteach["note"].lower()
    assert "no one course to charge them to" in reteach["note"]

    # It did not leak into the failed-run bucket, and neither course was charged.
    assert _calls_in(_group(usage, "failed_run")) == failed_before
    for course_id in course_ids:
        assert _course_group(usage, course_id) is None


def test_a_generation_run_that_really_failed_is_still_unattributed_because_it_failed(
    client, monkeypatch
):
    """Splitting re-teaching out must not cost "unattributed" its original meaning."""
    provider = OutlineThenFails()
    monkeypatch.setattr(main, "get_provider", lambda: provider)

    failed_before = _calls_in(_group(client.get("/usage").json(), "failed_run"))

    doomed = client.post("/courses/generate", json={"text": "Doomed source material."})
    assert doomed.status_code == 502
    assert provider.calls == 2

    failed = _group(client.get("/usage").json(), "failed_run")
    assert failed is not None
    assert failed["course_id"] is None
    assert failed["title"] is None
    assert failed["label"] == "Unattributed"
    assert failed["calls"] == failed_before + 2  # the outline, and the lesson that raised
    assert failed["note"] == main.GROUP_NOTES[main.GROUP_FAILED_RUN]
    assert "failed before its course could be saved" in failed["note"]


def test_only_generation_stages_are_covered_by_the_failed_run_sentence():
    """The failed-run sentence speaks for every stage that is not re-teaching.

    True today because the generation pipeline writes the only other stages, and that
    is the assumption the whole grouping rests on. A stage recorded from somewhere new
    would silently inherit a sentence about a generation run that failed, which is the
    exact shape of the bug this file exists for, so the covered set is pinned here.
    """
    assert set(generation.STAGES) == {"outline", "lesson"}
    assert remediation.REMEDIATION_STAGE not in generation.STAGES
    for stage in generation.STAGES:
        assert main._unattributed_group(stage) == main.GROUP_FAILED_RUN
    assert main._unattributed_group(remediation.REMEDIATION_STAGE) == main.GROUP_REMEDIATION


